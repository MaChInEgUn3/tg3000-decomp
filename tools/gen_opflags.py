"""Write tools/bench/opflags.h: the processor flags each 65816 opcode reads and writes,
derived from tools/listing.py's opcode table. Used by the bench's flag-liveness check.

    python3 -I tools/gen_opflags.py
"""
import importlib.util
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
spec = importlib.util.spec_from_file_location("listing", os.path.join(ROOT, "tools", "listing.py"))
L = importlib.util.module_from_spec(spec)
spec.loader.exec_module(L)
N, V, Z, C = 8, 4, 2, 1
NZ_ONLY = {"lda", "ldx", "ldy", "and", "ora", "eor", "inc", "dec", "inx", "iny", "dex", "dey",
           "tax", "tay", "txa", "tya", "tsx", "txy", "tyx", "tcd", "tdc", "tsc", "pla", "plx",
           "ply", "pld", "plb", "xba"}


def rw(mn, mode):
    if mn in ("adc", "sbc"):
        return C, N | V | Z | C
    if mn in ("rol", "ror"):
        return C, N | Z | C
    if mn in ("asl", "lsr", "cmp", "cpx", "cpy"):
        return 0, N | Z | C
    reads = {"bcc": C, "bcs": C, "beq": Z, "bne": Z, "bmi": N, "bpl": N, "bvc": V, "bvs": V,
             "php": N | V | Z | C, "brk": N | V | Z | C, "cop": N | V | Z | C}
    if mn in reads:
        return reads[mn], 0
    if mn in ("plp", "rti"):
        return 0, N | V | Z | C
    if mn in ("clc", "sec"):
        return 0, C
    if mn == "clv":
        return 0, V
    if mn == "xce":
        return C, C
    if mn == "bit":
        return 0, Z if mode == "immm" else N | V | Z
    if mn in ("trb", "tsb"):
        return 0, Z
    if mn in NZ_ONLY:
        return 0, N | Z
    return 0, 0  # rep/sep: from the operand at run time; txs/tcs and others: none


def main():
    rd, wr = zip(*(rw(mn, mode) for mn, mode in L.TABLE))
    out = ["// Generated by tools/gen_opflags.py: the processor flags each 65816 opcode reads and",
           "// writes (bits: N=8 V=4 Z=2 C=1). REP/SEP (C2/E2) depend on their operand and are",
           "// handled by the caller.", "#ifndef BENCH_OPFLAGS_H", "#define BENCH_OPFLAGS_H", "",
           "#include <stdint.h>", ""]
    for name, tab in (("opFlagsRead", rd), ("opFlagsWritten", wr)):
        out.append(f"static const uint8_t {name}[256] = {{")
        out += ["  " + ", ".join(f"{x:2d}" for x in tab[i:i + 16]) + "," for i in range(0, 256, 16)]
        out += ["};", ""]
    out += ["#endif", ""]
    with open(os.path.join(ROOT, "tools", "bench", "opflags.h"), "w") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
